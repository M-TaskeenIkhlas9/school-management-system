import pool from "./pool.js";

/** Run `work(conn)` in one transaction: committed if it returns, rolled back if it throws. */
export async function inTransaction(work) {
  const conn = await pool.getConnection();
  try {
    await conn.beginTransaction();
    const result = await work(conn);
    await conn.commit();
    return result;
  } catch (err) {
    await conn.rollback();
    throw err;
  } finally {
    conn.release();
  }
}
